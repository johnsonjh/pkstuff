/*****************************************************************************/

static unsigned long
msk32 (unsigned long val)
{
  return val & (unsigned long)0xFFFFFFFF;
}

/*****************************************************************************/

static unsigned long
crc32 (unsigned long crc, unsigned int val)
{
  unsigned int i;

  crc ^= (unsigned long)(val & (unsigned int)0xFF);

  for (i = (unsigned int)0; i < 8; ++i)
    {
      if ((crc & (unsigned long)1) != (unsigned long)0)
        {
          crc = (crc >> 1) ^ (unsigned long)0xEDB88320;
        }
      else
        {
          crc >>= 1;
        }

      crc = msk32 (crc);
    }

  return crc;
}

/*****************************************************************************/

static unsigned long
rl32 (unsigned long val, unsigned int cnt)
{
  val = msk32 (val);
  cnt &= (unsigned int)31;

  if (cnt == (unsigned int)0)
    {
      return val;
    }

  return msk32 ((val << cnt) | (val >> ((unsigned int)32 - cnt)));
}

/*****************************************************************************/

static void
fmt_b36 (unsigned long val, char out[8])
{
  static const char dig[] = "0123456789abcdefghijklmnopqrstuvwxyz";
  int pos;

  val = msk32 (val);

  for (pos = 6; pos >= 0; --pos)
    {
      unsigned long rem  = val % (unsigned long)36;
      val               /= (unsigned long)36;
      out[pos]           = dig[(unsigned int)rem];
    }

  out[7] = '\0';
}

/*****************************************************************************/

static unsigned int
read_name (unsigned char buf[MAXLEN])
{
  unsigned int len;
  int ch;

  len = (unsigned int)0;

  while ((ch = getchar ()) != EOF)
    {
      if (ch == '\n' || ch == '\r')
        {
          break;
        }

      if (len >= MAXLEN)
        {
          (void)fprintf (stderr, "NOTE: Company Name is too long.\n");

          return 0;
        }

      buf[len] = (unsigned char)((unsigned int)ch & (unsigned int)0xFF);
      ++len;
    }

  return len;
}

/*****************************************************************************/

static int
read_stamp (char stamp[4])
{
  unsigned int len;
  int ch;

  len = (unsigned int)0;

  while ((ch = getchar ()) != EOF)
    {
      if (ch == '\n' || ch == '\r')
        {
          break;
        }

      if (len < (unsigned int)3)
        {
          if (ch >= 'a' && ch <= 'z')
            {
              ch -= ('a' - 'A');
            }

          if (ch < 'A' || ch > 'Z')
            {
              while ((ch = getchar ()) != EOF && ch != '\n' && ch != '\r');

              return -1;
            }

          stamp[len] = (char)ch;
          ++len;
        }
      else
        {
          while ((ch = getchar ()) != EOF && ch != '\n' && ch != '\r');

          return -1;
        }
    }

  stamp[len] = '\0';

  if (len == (unsigned int)0)
    {
      return 0;
    }

  if (len != (unsigned int)3)
    {
      return -1;
    }

  return 1;
}

/*****************************************************************************/

static unsigned int
stamp_number (const char stamp[4])
{
  unsigned int n;
  unsigned int i;

  n = (unsigned int)0;

  for (i = (unsigned int)0; i < (unsigned int)3; ++i)
    {
      n = n * (unsigned int)26 + (unsigned int)(stamp[i] - 'A');
    }

  return n;
}

/*****************************************************************************/

typedef struct av_iterator
{
  unsigned int pos;
  unsigned long k;
} av_iterator;

/*****************************************************************************/

static void
av_iter_init (av_iterator *it)
{
  it->pos = (unsigned int)0;
  it->k   = (unsigned long)0;
}

/*****************************************************************************/

static unsigned long
av_iter_next (av_iterator *it)
{
  unsigned int shift;
  unsigned long delta;
  unsigned char b;

  delta = (unsigned long)0;
  shift = (unsigned int)0;

  do
    {
      b      = av_data[it->pos++];
      delta |= (unsigned long)(b & (unsigned char)0x7F) << shift;
      shift += (unsigned int)7;
    }
  while (b & (unsigned char)0x80);

  it->k += delta;

  return it->k * (unsigned long)1413 + (unsigned long)26;
}

/*****************************************************************************/

static unsigned int
av_code (unsigned long seed)
{
  return (unsigned int)((msk32 (seed) >> 11) & (unsigned long)0xFFFF);
}

/*****************************************************************************/

static int
find_first (unsigned int code, unsigned long *seed_out)
{
  unsigned int i;
  av_iterator it;

  av_iter_init (&it);

  for (i = (unsigned int)0; i < (unsigned int)AV_COUNT; ++i)
    {
      unsigned long seed = av_iter_next (&it);
      unsigned int c     = av_code (seed);

      if (c == code)
        {
          if (seed_out != (unsigned long *)0)
            {
              *seed_out = seed;
            }

          return 1;
        }
    }

  return 0;
}

/*****************************************************************************/

static void
fmt_stamp (unsigned long seed, char out[7])
{
  unsigned long rot;
  unsigned int l, d;

  rot = rl32 (seed, (unsigned int)7);

  l = (unsigned int)((rot >> 18) & (unsigned long)0x3FFF);

  out[0] = (char)('A' +  l / (unsigned int)676);
  out[1] = (char)('A' + (l / (unsigned int)26) % (unsigned int)26);
  out[2] = (char)('A' +  l % (unsigned int)26);

  d = (unsigned int)((rot & (unsigned long)0x3FFFF) / (unsigned long)0x107);

  out[3] = (char)('0' +  d / (unsigned int)100);
  out[4] = (char)('0' + (d / (unsigned int)10) % (unsigned int)10);
  out[5] = (char)('0' +  d % (unsigned int)10);
  out[6] = '\0';
}

