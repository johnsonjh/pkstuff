int
main (void)
{
  unsigned char name[MAXLEN];
  char requested[4], stamp[7];
  unsigned int len, n;
  unsigned long seed, uls = (unsigned long)sizeof (unsigned long);

  if ((uls * CHAR_BIT) < (unsigned long)32) /* //-V547 */
    {
      (void)fprintf (stderr, "ERROR: unsigned long <32 bits.\n");

      return 1;
    }

  (void)printf ("Company Name (less than 50 printable ASCII characters)? ");
  (void)fflush (stdout);

  len = read_name (name);

  if (len == 0)
    {
      (void)fprintf (stderr, "ERROR: Company Name is required.\n");

      return 1;
    }

  for (;;)
    {
      int rc;

      (void)printf (
        "AV Stamp (3 alphabetic characters or blank for random)? ");
      (void)fflush (stdout);

      rc = read_stamp (requested);

      if (rc == 0)
        {
          unsigned int candidate_count;
          unsigned int i;
          unsigned int random_ordinal;
          av_iterator it;

          candidate_count = (unsigned int)0;

          av_iter_init (&it);

          for (i = (unsigned int)0; i < (unsigned int)AV_COUNT; ++i)
            {
              seed = av_iter_next (&it);
              n = av_code (seed);

              if (n > (unsigned int)17575)
                {
                  continue;
                }

              fmt_stamp (seed, stamp);

              if (stamp_number (stamp) != n)
                {
                  continue;
                }

              ++candidate_count;
            }

          if (candidate_count == (unsigned int)0)
            {
              (void)fprintf (stderr, "ERROR: No randomizable AV entries.\n");

              return 1;
            }

          srand ((unsigned int)time ((time_t *)0));
          random_ordinal = (unsigned int)(rand () % candidate_count);

          av_iter_init (&it);

          for (i = (unsigned int)0; i < (unsigned int)AV_COUNT; ++i)
            {
              seed = av_iter_next (&it);
              n = av_code (seed);

              if (n > (unsigned int)17575)
                {
                  continue;
                }

              fmt_stamp (seed, stamp);

              if (stamp_number (stamp) != n)
                {
                  continue;
                }

              if (random_ordinal == (unsigned int)0)
                {
                  break;
                }

              --random_ordinal;
            }

          fmt_stamp (seed, stamp);

          break;
        }

      {
        const char *erl = "ERROR: Requested characters cannot be used.\n";

        if (rc < 0)
          {
            (void)fprintf (stderr, erl); /* //-V618 */

            continue;
          }

        n = stamp_number (requested);

        if (n > (unsigned int)17575)
          {
            (void)fprintf (stderr, erl); /* //-V618 */

            continue;
          }

        if (!find_first (n, &seed))
          {
            (void)fprintf (stderr, erl); /* //-V618 */

            continue;
          }

      }

      break;
    }

  {
    unsigned char fold[4];
    unsigned long fld32, crc, s1, s2;
    char txt1[8], txt2[8];

    fold[0] = fold[1] = fold[2] = fold[3] = (unsigned char)0;
    crc = seed;

    for (n = (unsigned int)0; n < len; ++n)
      {
        unsigned int val;

        val = (unsigned int)name[n];

        fold[n & (unsigned int)3] =
          (unsigned char)(fold[n & (unsigned int)3] ^ name[n]);

        crc = crc32 (crc, val);
      }

    fld32 = (unsigned long)fold[0] |
           ((unsigned long)fold[1] << 8) |
           ((unsigned long)fold[2] << 16) |
           ((unsigned long)fold[3] << 24);

    fld32 = msk32 (fld32);

    s1 = msk32 (seed ^ fld32);

    crc = msk32 (~crc);
    crc = rl32 (crc, (unsigned int)(seed & (unsigned long)0x1F));

    s2 = msk32 (crc ^ fld32);

    fmt_b36 (s1, txt1);
    fmt_b36 (s2, txt2);
    fmt_stamp (seed, stamp);

    (void)printf ("\nSerial 1 : %s", txt1);
    (void)printf ("\nSerial 2 : %s", txt2);
    (void)printf ("\nAV Stamp : %s\n", stamp);
  }

  return 0;
}

