  char requested[7], stamp[7];
  unsigned int len, n;
  unsigned long seed, uls = (unsigned long)sizeof (unsigned long);

  if ((uls * CHAR_BIT) < (unsigned long)32) /* //-V547 */
    {
      (void)fprintf (stderr, "ERROR: unsigned long <32 bits.\n");

      return EXIT_FAILURE;
    }

  (void)printf ("\nMAKEAV:");
  (void)printf (" PKZIP 2.04/2.06/2.50 Authenticity Verification Generator\n");
